# Работа связанного списка без циклов
class Node:
    def __init__(self,data):
        self.data=data
        self.next=None


a=Node(3)
b=Node(5)
a.data=4
a.next=b
while a:
    print(a.next, end=" ") # Если атрибуту или переменной дать значение обьекта какого либо класса, то эта переменная будет хранить в себе cсылку на тот обьект. Изменения через одну переменную будут видны через другую
    a=a.next
