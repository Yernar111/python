# Малая теорема Ферма для вычисления остатка от деления числа на модуль с использованием формулы a^(p-1) = 1 (mod p). p-простое число, a и p взаимно простые числа
def gcd(a,b):
    if b==0:
        return a
    return gcd(b,a%b)

a=int(input()) # Основание
n=int(input()) # Показатель степени
p=int(input()) # Простое число на которое мы хотим поделить и найти остаток
if (gcd(n,p)==1):
    print(pow(a, n%(p-1))%p) # Остаток
else:
    print("Impossible to apply")
