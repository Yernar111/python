# При обычном возведении в степень операция умножения выполняется О(n) раз (n показатель степени), а при быстром(бинарном) возведении в степень за О(log n) раз
# Это получается благодаря тому что мы делим пополам четный показатель степени, а нечетный показатель приводим к четному 
def check(a,n):
    if n==1:
        return a
    if n%2==0:
        m=check(a,n//2)
        return m*m
    return a*check(a,n-1)


a=int(input())
n=int(input())
print(check(a,n))