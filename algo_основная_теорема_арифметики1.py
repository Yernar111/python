# Любое число можно представить произведением простых уникальным способом
n=int(input())
a=[]
i=2
while i<n:
    if n%i==0: # Проверять является ли i простым - необязательно
        while n%i==0:
            a.append(i)
            n//=i # Уменьшаем N деля ее на простые числа
    i+=1
if n>1: # Если после всех операции n остался больше 1 то он сам по себе является простым
    a.append(n)

print(a)

