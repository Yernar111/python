# Задача о ступеньках с использованием рекурсии и мемоизации. 
def check(n,k,a={}):
    if n<=1:
        return 1
    if n in a:
        return a[n]
    m=0; i=1
    while i<=min(n,k): # Если ступенька n на которую мы хотим попасть, меньше чем колво ступенек которые мы можем перешагивать. То наш лимит перешагивании будет n(чтобы не получилось отрицательное значение)
        m+=check(n-i,k) 
        i+=1
    a[n]=m
    return a[n]


n=int(input())
k=int(input())
print(check(n,k))